CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(60) NOT NULL UNIQUE,
    keycloak_user_id VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL,
    payment_status VARCHAR(30) NOT NULL,
    inventory_status VARCHAR(30) NOT NULL,
    shipping_status VARCHAR(30) NOT NULL,
    subtotal NUMERIC(14, 2) NOT NULL,
    shipping_fee NUMERIC(14, 2) NOT NULL,
    total_amount NUMERIC(14, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    payment_method VARCHAR(40),
    payment_reference VARCHAR(120),
    shipment_id VARCHAR(120),
    carrier VARCHAR(120),
    tracking_number VARCHAR(120),
    failure_reason VARCHAR(1000),
    customer_name VARCHAR(120) NOT NULL,
    customer_email VARCHAR(180) NOT NULL,
    customer_phone VARCHAR(30) NOT NULL,
    shipping_line1 VARCHAR(250) NOT NULL,
    shipping_line2 VARCHAR(250),
    shipping_city VARCHAR(100) NOT NULL,
    shipping_state VARCHAR(100) NOT NULL,
    shipping_pincode VARCHAR(20) NOT NULL,
    shipping_country VARCHAR(80) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    confirmed_at TIMESTAMP,
    cancelled_at TIMESTAMP,
    delivered_at TIMESTAMP
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    sku VARCHAR(80) NOT NULL,
    product_name_snapshot VARCHAR(200) NOT NULL,
    unit_price_snapshot NUMERIC(14, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    quantity INT NOT NULL,
    line_total NUMERIC(14, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);

CREATE INDEX idx_orders_keycloak_user_id ON orders(keycloak_user_id);
CREATE INDEX idx_orders_status ON orders(status);
CREATE INDEX idx_orders_order_number ON orders(order_number);
CREATE INDEX idx_order_items_order_id ON order_items(order_id);
CREATE INDEX idx_order_items_product_id ON order_items(product_id);
